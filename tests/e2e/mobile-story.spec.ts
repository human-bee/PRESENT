import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { test, expect } from '@playwright/test';
import type { RoomObject } from '../../shared/room';

test('mobile portrait debate, shared dice, and reload recovery', async ({ browser, baseURL }, info) => {
  test.setTimeout(180000);
  const roomId = randomBytes(16).toString('hex');
  const mobileContext = await browser.newContext({ baseURL, viewport: { width: 390, height: 844 }, deviceScaleFactor: 1, isMobile: true, hasTouch: true, recordVideo: { dir: info.outputPath('mobile'), size: { width: 390, height: 844 } } });
  const peerContext = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 } });
  for (const [context, name] of [[mobileContext, 'Maya · mobile'], [peerContext, 'Alex · desktop']] as const) await context.addInitScript(name => { if (window === window.top) localStorage.setItem('present:name', name); }, name);
  const mobile = await mobileContext.newPage(), peer = await peerContext.newPage();
  const errors: string[] = [];
  for (const page of [mobile, peer]) page.on('pageerror', e => errors.push(e.message));
  const pause = () => process.env.PRESENT_RECORD_DEMO === '1' ? mobile.waitForTimeout(2300) : Promise.resolve(); // Watchable pacing after assertions.
  const proof = { roomId, viewport: { width:390, height:844 }, browser: 'Chromium with touch and mobile emulation', physicalPhone: false, steps: [] as string[] };
  const step = (value: string) => { proof.steps.push(value); console.log(value); };
  try {
    await Promise.all([mobile.goto(`/r/${roomId}`), peer.goto(`/r/${roomId}`)]);
    await expect(mobile.locator('.room-status')).toHaveText('here, together');
    await mobile.getByRole('textbox', { name:'Room name', exact:true }).fill('Mobile game night');
    await mobile.getByRole('textbox', { name:'Room name', exact:true }).blur();
    await pause();
    await mobile.getByRole('button', { name:'◈ Activities', exact:true }).tap();
    await mobile.locator('.activity-template-grid button').filter({ has: mobile.getByText('Debate', {exact:true}) }).tap();
    const m = mobile.getByRole('dialog', { name:'Debate room' });
    await expect(m.getByRole('heading', { name:'A good disagreement', exact:true })).toBeVisible();
    await pause();
    await m.getByRole('button', {name:'Adapt activity', exact:true}).tap();
    await m.getByLabel('Room topic', {exact:true}).fill('Should our game night be cooperative?');
    await m.getByLabel('Follow the conversation', {exact:true}).uncheck();
    await m.getByRole('button', {name:'Save adaptation', exact:true}).tap();
    await peer.getByRole('button', {name:'Open Debate', exact:true}).click();
    const p = peer.getByRole('dialog', {name:'Debate room'});
    await expect(p.getByRole('heading', {name:'Should our game night be cooperative?', exact:true})).toBeVisible();
    await m.getByRole('region', {name:'For side', exact:true}).getByRole('button', {name:'Take a seat', exact:true}).tap();
    await p.getByRole('region', {name:'Against side', exact:true}).getByRole('button', {name:'Take a seat', exact:true}).click();
    await m.getByRole('textbox', {name:'Add to the conversation'}).fill('Cooperative games help everyone join in.');
    await m.getByRole('button', {name:'Add thought ↗', exact:true}).tap();
    await expect(p.getByRole('log')).toContainText('Cooperative games help everyone join in.');
    await p.getByRole('textbox', {name:'Add to the conversation'}).fill('A friendly competition can also bring us together.');
    await p.getByRole('button', {name:'Add thought ↗', exact:true}).click();
    await expect(m.getByRole('log')).toContainText('A friendly competition can also bring us together.');
    await m.getByRole('log').scrollIntoViewIfNeeded();
    await pause();
    step('Mobile host launches and adapts a debate; opposing desktop participant receives and replies.');
    await m.locator('.conversation-entry').filter({hasText:'Cooperative games help everyone join in.'}).getByRole('button', {name:'Capture claim', exact:true}).tap();
    const claim = p.locator('.claim-card').filter({hasText:'Cooperative games help everyone join in.'});
    await claim.getByRole('button', {name:'Correct / discuss', exact:true}).click();
    await claim.getByLabel('Claim wording', {exact:true}).fill('Cooperative games can help new players join in.');
    await claim.getByLabel('Reason', {exact:true}).fill('Different players enjoy different styles.');
    await claim.getByRole('button', {name:'Save correction', exact:true}).click();
    await expect(m.locator('.claim-proposition')).toHaveText('Cooperative games can help new players join in.');
    await m.locator('.claim-proposition').scrollIntoViewIfNeeded();
    await pause();
    await mobile.screenshot({path:info.outputPath('mobile-debate.png')});
    step('Desktop correction arrives on the mobile claim card.');
    await mobile.reload();
    await expect(m.locator('.claim-proposition')).toHaveText('Cooperative games can help new players join in.');
    await m.locator('.claim-proposition').scrollIntoViewIfNeeded();
    await pause();
    step('Reload preserves the shared conversation and corrected claim.');
    await mobile.getByRole('button', {name:'Back to canvas ↙', exact:true}).tap();
    await peer.getByRole('button', {name:'Back to canvas ↙', exact:true}).click();
    await expect(m).toHaveCount(0);
    await mobile.getByRole('button', {name:'Fit everything', exact:true}).tap();
    await expect(mobile.locator('.native-canvas .room-activity-debate')).toBeVisible();
    await mobile.getByRole('button', {name:'Hide drawing tools', exact:true}).tap();
    await expect(mobile.getByRole('toolbar', {name:'Tools', exact:true})).toHaveCount(0);
    await pause();
    await mobile.getByRole('button', {name:'Add to room', exact:true}).tap();
    await mobile.getByRole('button', {name:'Dice table Roll common dice with a shared, attributed history.', exact:true}).tap();
    const objects = async (): Promise<RoomObject[]> => (await (await mobile.request.get(`/api/room/${roomId}`)).json()).room.objects;
    await expect.poll(async () => (await objects()).filter(o => o.data.capability === 'dice').length).toBe(1);
    const dice = (await objects()).find(o => o.data.capability === 'dice');
    if (!dice) throw new Error('The mobile dice widget was not saved.');
    await mobile.goto(`/r/${roomId}?focus=${dice.id}`);
    await peer.goto(`/r/${roomId}?focus=${dice.id}`);
    const mf = mobile.frameLocator('iframe[title="Dice table"]'), pf = peer.frameLocator('iframe[title="Dice table"]');
    await mf.getByLabel('Number of dice').selectOption('2');
    await mf.getByLabel('Dice sides').selectOption('20');
    await pause();
    await mf.getByRole('button', {name:'Roll dice', exact:true}).tap();
    await expect(mf.locator('#latest output')).toBeVisible();
    const roll = await mf.locator('#latest output').innerText();
    expect(Number(roll)).toBeGreaterThanOrEqual(2);
    expect(Number(roll)).toBeLessThanOrEqual(40);
    await expect(pf.locator('#latest output')).toHaveText(roll);
    await pause();
    await pf.getByRole('button', {name:'Roll dice', exact:true}).click();
    await mf.getByText('Shared roll history', {exact:true}).tap();
    await expect(mf.locator('#history > div')).toHaveCount(2);
    await pause();
    await mobile.screenshot({path:info.outputPath('mobile-dice.png')});
    step('Mobile touches operate an embedded canvas dice widget; both participants see both rolls.');
    await mobile.reload();
    await mf.getByText('Shared roll history', {exact:true}).tap();
    await expect(mf.locator('#history > div')).toHaveCount(2);
    await pause();
    await mobile.getByRole('button', {name:'Show drawing tools', exact:true}).tap();
    await mobile.getByRole('button', {name:'Fit everything', exact:true}).tap();
    await mobile.getByRole('button', {name:'Hide drawing tools', exact:true}).tap();
    await pause();
    await mobile.screenshot({path:info.outputPath('mobile-canvas.png')});
    expect(errors).toEqual([]);
    expect(await mobile.evaluate(() => window.innerWidth)).toBe(390);
    step('Both widgets and dice history survive reload; no unexpected browser errors.');
    writeFileSync(info.outputPath('proof.json'), JSON.stringify({...proof, errors, status:'passed'}, null, 2));
  } finally {
    await Promise.all([mobileContext.close(), peerContext.close()]);
  }
});
